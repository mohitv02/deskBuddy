def osc(f0, f1, step, a, b, start=0.0, end=0.0):
    """alternating keys a,b,a,b between f0..f1 starting/ending at given values"""
    keys = [(f0, start)]; f = f0 + step; i = 0
    while f < f1:
        keys.append((f, a if i % 2 == 0 else b)); f += step; i += 1
    keys.append((f1, end)); return keys
def mirror(keys):
    out = []
    for k in keys:
        v = k[1]
        v = (-v[0], v[1]) if isinstance(v, tuple) else -v
        out.append((k[0], v) + tuple(k[2:]))
    return out
def smooth(u): return u * u * (3 - 2 * u)
def ease_io(u): return bez_y(EIO, max(0, min(1, u)))
def ease_out(u): return bez_y(EOUT, max(0, min(1, u)))

def fx_path(c, name, kind, parent, p0, p1, f0, f1, peak=1.0, rot=0.0, wob=0.0, fade_in=0.18, fade_out=0.3,
            grow=(0.4, 1.0), pop=False, step=2):
    """effect travels p0->p1 during [f0,f1] (eased), scales, fades in/out; invisible outside"""
    c.effect(name, kind, p0, parent)
    def u(f): return max(0.0, min(1.0, (f - f0) / (f1 - f0)))
    def pos(f):
        q = ease_out(u(f))
        return ((p1[0] - p0[0]) * q + wob * math.sin(u(f) * math.pi * 2), (p1[1] - p0[1]) * q)
    def sc(f):
        q = u(f)
        if pop:
            v = (1.25 * ease_out(q / 0.25)) if q < 0.25 else (1.25 - 0.25 * ease_io((q - 0.25) / 0.15) if q < 0.4 else 1.0)
            v *= peak
        else:
            v = (grow[0] + (grow[1] - grow[0]) * ease_out(q)) * peak
        return (v, v)
    def op(f):
        q = u(f)
        if f < f0 or f > f1: return 0.0
        if q < fade_in: return ease_io(q / fade_in)
        if q > 1 - fade_out: return ease_io((1 - q) / fade_out)
        return 1.0
    c.sample(name, 'p', pos, f0, f1, step)
    c.sample(name, 's', sc, f0, f1, step)
    c.sample(name, 'o', op, f0, f1, step)
    if f0 > 0: c.k(name, 'o', [(0, 0)])
    if f1 < c.N: c.k(name, 'o', [(c.N, 0)])
    if rot: c.sample(name, 'r', lambda f: rot * u(f), f0, f1, step)

def fx_pop(c, name, kind, parent, p, f0, f1, peak=1.0, pulse=0.0, pulse_period=8, rot=0.0, step=1):
    """pops in (overshoot), optional pulse, shrinks out at the end"""
    c.effect(name, kind, p, parent)
    def sc(f):
        if f <= f0 or f >= f1: return (0.0, 0.0)
        a = f - f0; b = f1 - f
        if a < 4: v = 1.25 * ease_out(a / 4)
        elif a < 8: v = 1.25 - 0.25 * ease_io((a - 4) / 4)
        else: v = 1.0 + pulse * math.sin((a - 8) / pulse_period * 2 * math.pi) ** 2
        if b < 5: v *= ease_io(b / 5)
        return (v * peak, v * peak)
    c.sample(name, 's', sc, max(0, f0 - 1), min(c.N, f1 + 1), step)
    c.vis(name, [(0, 0), (f0, 1)] + ([(f1 + 1, 0)] if f1 + 1 < c.N else []))
    if rot: c.sample(name, 'r', lambda f: rot * math.sin(max(0, f - f0) / 10 * math.pi), f0, f1, step)

